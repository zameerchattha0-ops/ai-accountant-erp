"""FIX for the adversarial-probe BOTH gap (2026-10-21).

The earlier probe's 'ambiguous' cases all came back loc=NEITHER because no
item existed in BOTH registers — so the true BOTH branch was never exercised
against live data.  This seeds a REAL collision (one name as BOTH a stock
product and a fixed asset), runs the live item-nature analyst on it, and
verifies it reports BOTH and ASKS.  Cleans up its own fixtures after.

Usage: venv\\Scripts\\python scripts/_probe_both_collision.py
"""
from __future__ import annotations

import asyncio
import random
import string
import sys
import uuid
from pathlib import Path

ERP_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ERP_ROOT))

ORG = "00000000-0000-4000-8000-000000000010"
ORG_UUID = uuid.UUID(ORG)
SFX = "".join(random.choices(string.ascii_lowercase, k=4))
NAME = f"E2E Dual {SFX}"   # exists as BOTH a product and an asset

RESULTS: list[tuple[str, bool, str]] = []


def record(name, ok, detail=""):
    RESULTS.append((name, bool(ok), detail))
    print(f"  [{'PASS' if ok else 'FAIL'}] {name}" + (f" — {detail}" if detail else ""), flush=True)
    return bool(ok)


async def main() -> int:
    from app.config import get_settings
    settings = get_settings()
    settings.llm_item_nature_enabled = True

    from app.database import insert_one, fetch_many, delete_one

    # ---- seed a REAL BOTH collision --------------------------------------
    # Use the SERVICE layer for the product so product_code (NOT NULL) is
    # generated by next_document_number — a raw insert_one bypasses it.
    from app.services import product_service
    prod = await product_service.create(
        ORG_UUID, name=NAME, is_stock_tracked=True, unit_price=1000.0,
    )
    asset = await insert_one("fixed_assets", data={
        "organization_id": ORG, "name": NAME,
        "purchase_date": "2026-10-21", "purchase_cost": 1000.0,
        "useful_life_years": 5, "depreciation_method": "STRAIGHT_LINE",
    })
    print(f"seeded BOTH: product={prod.get('id')} asset={asset.get('id')} name={NAME!r}\n")

    try:
        from app.item_nature_analyst import analyse_item_nature

        # registers fetched live inside the analyst
        verdict = await analyse_item_nature(
            organization_id=ORG_UUID, item=NAME, intent="record_purchase",
            message=f"I bought a {NAME}", products=None, assets=None,
        )
        if verdict is None:
            record("analyst_ran", False, "returned None")
            return 1
        record("analyst_ran", True, "")
        record("location_is_BOTH", verdict["location"] == "BOTH",
               f"location={verdict['location']}")
        record("asks_when_in_both", verdict["needs_question"] is True,
               f"needs_question={verdict['needs_question']} nature={verdict['proposed_nature']}")
        record("grounded_to_product", bool(verdict["matched_product"]),
               f"product={(verdict['matched_product'] or {}).get('name')!r}")
        record("grounded_to_asset", bool(verdict["matched_asset"]),
               f"asset={(verdict['matched_asset'] or {}).get('name')!r}")
        if verdict["needs_question"]:
            record("question_is_substantive", bool(verdict["question"]),
                   f"question={verdict['question']!r}")

        # ---- purpose-of-use DISAMBIGUATION on the SAME collision ---------
        v2 = await analyse_item_nature(
            organization_id=ORG_UUID, item=NAME, intent="record_purchase",
            message=f"I bought a {NAME} for resale to customers in our shop",
            products=None, assets=None,
        )
        record("purpose_disambiguates_BOTH",
               v2 is not None and v2["proposed_nature"] == "INVENTORY"
               and v2["needs_question"] is False,
               f"nature={(v2 or {}).get('proposed_nature')} ask={(v2 or {}).get('needs_question')}")
    finally:
        # ---- cleanup fixtures (never leave test junk) ---------------------
        try:
            await delete_one("products", row_id=uuid.UUID(str(prod["id"])),
                             organization_id=ORG_UUID)
            await delete_one("fixed_assets", row_id=uuid.UUID(str(asset["id"])),
                             organization_id=ORG_UUID)
            print("\ncleaned up seeded product + asset")
        except Exception as exc:  # noqa: BLE001
            print(f"\nCLEANUP WARNING: {exc}")

    passed = sum(1 for _, ok, _ in RESULTS if ok)
    total = len(RESULTS)
    print(f"\n== RESULT: {passed}/{total} passed ==", flush=True)
    for name, ok, detail in RESULTS:
        if not ok:
            print(f"  FAILED: {name} — {detail}", flush=True)
    return 0 if passed == total else 1


if __name__ == "__main__":
    raise SystemExit(asyncio.run(main()))
